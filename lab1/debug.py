# --- Фрагмент А: сумма чисел 2 и 3 ---
first = "2"
second = "3"
print("А. Сумма:", int(first) + int(second))   # 5

# --- Фрагмент Б: возраст через год ---
age_str = "17"
print("Б. Возраст через год:", int(age_str) + 1)   # 18

# --- Фрагмент В: среднее трёх чисел ---
first_n = 4
second_n = 7
third_n = 10
